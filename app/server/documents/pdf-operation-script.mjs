  "import json",
  "import sys",
  "",
  "import fitz",
  "from pypdf import PdfReader",
  "",
  "input_path, output_path = sys.argv[1:3]",
  "payload = json.loads(sys.stdin.read())",
  "document = fitz.open(input_path)",
  "changed_pages = set()",
  "warnings = []",
  "",
  "def page_indices(pages):",
  "    return [int(page) - 1 for page in pages] if pages else list(range(len(document)))",
  "",
  "for operation in payload['operations']:",
  "    operation_type = operation['type']",
  "    if operation_type == 'delete_pages':",
  "        for page_index in sorted(page_indices(operation['pages']), reverse=True):",
  "            document.delete_page(page_index)",
  "        changed_pages.update(range(1, len(document) + 1))",
  "    elif operation_type == 'reorder_pages':",
  "        document.select(page_indices(operation['order']))",
  "        changed_pages.update(range(1, len(document) + 1))",
  "    elif operation_type == 'rotate_pages':",
  "        for page_index in page_indices(operation['pages']):",
  "            page = document[page_index]",
  "            page.set_rotation((page.rotation + operation['degrees']) % 360)",
  "        changed_pages.update(operation['pages'])",
  "    elif operation_type == 'insert_blank_page':",
  "        document.new_page(",
  "            pno=operation['afterPage'],",
  "            width=operation.get('width') or 595,",
  "            height=operation.get('height') or 842,",
  "        )",
  "        changed_pages.update(range(max(1, operation['afterPage']), len(document) + 1))",
  "    elif operation_type == 'merge_document':",
  "        source = fitz.open(payload['documents'][operation['sourceDocumentId']])",
  "        try:",
  "            document.insert_pdf(source, start_at=operation['afterPage'])",
  "        finally:",
  "            source.close()",
  "        changed_pages.update(range(max(1, operation['afterPage']), len(document) + 1))",
  "    elif operation_type in ('redact_text', 'replace_text'):",
  "        matches = [",
  "            (page_index, rectangle)",
  "            for page_index in page_indices(operation.get('pages'))",
  "            for rectangle in document[page_index].search_for(operation['query'])",
  "        ]",
  "        expected = operation.get('expectedOccurrences')",
  "        if expected is not None and len(matches) != expected:",
  "            raise ValueError(",
  "                'Expected ' + str(expected) + ' occurrences but found ' + str(len(matches)) + '.'",
  "            )",
  "        for page_index, rectangle in matches:",
  "            document[page_index].add_redact_annot(rectangle, fill=(1, 1, 1))",
  "        for page_index in sorted({page_index for page_index, _ in matches}):",
  "            document[page_index].apply_redactions()",
  "            changed_pages.add(page_index + 1)",
  "        if operation_type == 'replace_text':",
  "            for page_index, rectangle in matches:",
  "                document[page_index].insert_text(",
  "                    (rectangle.x0, rectangle.y1 - 2),",
  "                    operation['replacement'],",
  "                    fontsize=operation.get('fontSize') or 11,",
  "                    overlay=True,",
  "                )",
  "            warnings.append('Replacement typography may differ from the original font.')",
  "    elif operation_type == 'add_text':",
  "        page = document[operation['page'] - 1]",
  "        rectangle = fitz.Rect(",
  "            operation['x'],",
  "            operation['y'],",
  "            operation['x'] + operation['width'],",
  "            operation['y'] + operation['height'],",
  "        )",
  "        page.insert_textbox(",
  "            rectangle,",
  "            operation['text'],",
  "            fontsize=operation['fontSize'],",
  "            align={'left': 0, 'center': 1, 'right': 2}.get(operation.get('align', 'left'), 0),",
  "            overlay=True,",
  "        )",
  "        changed_pages.add(operation['page'])",
  "    elif operation_type == 'add_image':",
  "        page = document[operation['page'] - 1]",
  "        rectangle = fitz.Rect(",
  "            operation['x'],",
  "            operation['y'],",
  "            operation['x'] + operation['width'],",
  "            operation['y'] + operation['height'],",
  "        )",
  "        page.insert_image(",
  "            rectangle,",
  "            filename=payload['images'][operation['imageId']],",
  "            overlay=True,",
  "        )",
  "        changed_pages.add(operation['page'])",
  "    elif operation_type == 'watermark':",
  "        for page_index in page_indices(operation.get('pages')):",
  "            page = document[page_index]",
  "            page.insert_text(",
  "                (page.rect.width / 2, page.rect.height / 2),",
  "                operation['text'],",
  "                fontsize=32,",
  "                color=(0.5, 0.5, 0.5),",
  "                fill_opacity=operation['opacity'],",
  "                overlay=True,",
  "            )",
  "            changed_pages.add(page_index + 1)",
